BEGIN;

ALTER TABLE device
    ADD COLUMN IF NOT EXISTS print_dots integer
        CHECK (print_dots IS NULL OR (print_dots BETWEEN 200 AND 832 AND print_dots % 8 = 0));

COMMIT;
