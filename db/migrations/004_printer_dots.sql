-- ซึ่งถูกเฉพาะเครื่อง 203 dpi — เครื่อง 180 dpi อย่าง Epson TM-T88 ทุกรุ่น
-- พิมพ์กระดาษ 80 มม. ได้แค่ 512 จุด ส่งเกินไปขอบขวาจะขาดหาย
--
-- NULL = ใช้ค่ามาตรฐานตามขนาดกระดาษ
